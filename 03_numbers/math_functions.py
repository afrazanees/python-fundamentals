# 1. Round Number Function - round the number
print(round(2.9))
print(round(2.2))


# 2. Absolute Value Function - return the absolute value
print(abs(-1.2))

# Python have few built-in math functions. If you want to do complex mathematical 
# calculations, you have to use "Math Module".

# "Module" is like a separate file, which has some python code.

# To use any module, you have to "Import it."

import math 
# Here "math" is an "Object". So we use functions from "Math module" as we call functions from 
# "math module" just as same.

# 3. Ciel Function - Gives the closest integer greater than or equal to x
print(math.ceil(2.2))

# 4. Floor Function - Gives the closest integer lesser than or equal to x
print(math.floor(2.2))

# 5. Factorial Function - Gives factorial of a number
print(math.factorial(5))

# 6. Remainder Function - Gives the remainder
print(math.remainder(10,3))