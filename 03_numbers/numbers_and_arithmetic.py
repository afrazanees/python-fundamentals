# Following are the ways to represent numbers in python

# 1. Simple Number
x = 1

# 2. Float/Decimal Number
x = 1.1

# 3. Complex Numbers
x = 1 + 2j          # Instead of "i" for "Imaginary Number", we use "j" in Python


# Standard Arithimatic Operations can also be performed in Python
# 1. Addition
print(10 + 3)

# 2. Subraction
print(10 - 3)

# 3. Multiplication
print(10 * 3)

# 4. Division
# In python, we have two types of divison
# i. To get "Floating Point" number in output
print(10 / 3)
# ii. To get "Integer" number in output
print(10 // 3)

# 5. Moduolus - To get remainder of division
print(10 % 3)

# 6. Exponent - Which is "LEFT" to the power of "RIGHT"
print(10 ** 3)          # It is read as "10 to the power of 3"

# 7. Augmented Assignment Operator
y = 10
y = 10 + 3
print(y)
# We use "Augmented Assignment Operator" for simpler approach
y += 3
print(y)

# Any Arithmetic operator can be used with "Augment Asignment Operator"
