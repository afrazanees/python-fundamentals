# We use "Comparison Operators" to compare values.
# Examples
# 1. Greater than Operator
print(10 > 3)

# 2. Greater than OR Equal To Operator
print(10 >= 3)

# 3. Lesser than Operator
print(10 < 3)

# 4. Lesser than OR Equal To Operator
print(10 <= 3)

# 5. Equals To Operator
print(10 == 3)
print(10 == 10)
print(10 == "10")

# 6. Not Equals To Operator.
print(10 != 3)
print(10 != 10)
print(10 != "10")


# We can also use this camparison operators with "Strings".
# NOTE that string comparison is based on the alphabetical ASCII (Unicode) values of characters.

# Example
print ("bag" > "Apple")   # The ASCII value of "b" is 98 and "A" is 65. So it will return "True".
print ("bag" == "BAG")  

