numbers = [5, 2, 8, 1, 3]

numbers.sort()
print(numbers)

numbers = [10, 1, 15, 90, 22]
sorted_numbers = sorted(numbers)
print(sorted_numbers)
print(numbers)

# Difference between sort() and sorted():
# sort() sorts the list in-place and returns None, while sorted() returns a new sorted list 
# and leaves the original list unchanged.
