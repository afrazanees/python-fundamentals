# Python has many built-in functions. But we can create our own custom functions.
# Custom-Functions are needed because in real-applications the code may consists of hundreds or
# thousands of lines of code. Instead of writing all code in one file, we break that code into smaller
# more maintable and reusable chunks. These chunks are known as functions.

# Defining a funtion
def greet():
    print("Hi there!")
    print("Welcome aboard")


# Calling a function
greet()